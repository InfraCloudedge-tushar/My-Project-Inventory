import { ProjectParameters, ScenarioPreset, ShipmentBatch } from '../types/supplyChain';

export function generateShipmentsFromParams(params: ProjectParameters): ShipmentBatch[] {
  const totalModules = Math.ceil((params.farmCapacityMW * 1_000_000) / params.moduleWattageWp);
  const totalContainers = Math.ceil(totalModules / params.modulesPerContainer);

  // Target ~12-16 coordinated release waves over the procurement window
  const waveCount = Math.min(18, Math.max(8, Math.round(totalContainers / 28)));
  const containersPerWaveBase = Math.floor(totalContainers / waveCount);
  const remainder = totalContainers % waveCount;

  // Spread releases from Day 1 up to ~75% of installation duration so buffer builds ahead of Day installStartDay
  const installDurationDays = Math.ceil(totalModules / Math.max(1, params.dailyInstallRate));
  const releaseSpanDays = Math.max(30, Math.round(installDurationDays * 0.85));
  const intervalDays = Math.max(2, Math.round(releaseSpanDays / waveCount));

  const batches: ShipmentBatch[] = [];
  for (let i = 0; i < waveCount; i++) {
    const containers = containersPerWaveBase + (i < remainder ? 1 : 0);
    if (containers <= 0) continue;
    batches.push({
      batchId: `WV-${String(i + 1).padStart(2, '0')}`,
      releaseDay: 1 + i * intervalDays,
      containers,
      modules: containers * params.modulesPerContainer,
      priorityMode: i < 2 ? 'buffer' : 'standard',
    });
  }
  return batches;
}

